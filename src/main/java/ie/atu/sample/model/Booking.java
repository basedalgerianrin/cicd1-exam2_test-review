package ie.atu.sample.model;

import jakarta.persistence.*;
import lombok.Data;
import lombok.NoArgsConstructor;

// One row in the Booking Service's own H2 database.
// The room itself lives in the Room Service, so we only store its ID here.
@Entity
@Data               // Lombok: generates getters, setters, toString, equals, hashCode
@NoArgsConstructor  // JPA needs an empty constructor
public class Booking {

    @Id
    @GeneratedValue(strategy = GenerationType.IDENTITY)
    private Long id;            // booking ID, generated by the database

    private String organiserName;
    private int attendeeCount;
    private Long roomId;
    private String status = "ACTIVE";   // every new booking starts as ACTIVE
}
